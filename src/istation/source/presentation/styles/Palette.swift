import SwiftUI

/// Every color the apps draw with, named for its role.
public enum Palette {
    /// The player's screen when nothing is running.
    public static let screen = Color.black
    /// Text drawn on the screen.
    public static let onScreen = Color.white
    /// Text that explains rather than names.
    public static let secondaryText = Color.secondary
}
